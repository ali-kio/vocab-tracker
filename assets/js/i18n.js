function t(key, vars){
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
  let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.ar[key] !== undefined ? TRANSLATIONS.ar[key] : key);
  if(vars){
    Object.keys(vars).forEach(k=>{ str = str.split('{'+k+'}').join(vars[k]); });
  }
  return str;
}

function applyStaticTranslations(){
  document.title = t('doc_title');
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
}

function applyLanguage(lang){
  currentLang = lang;
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang==='ar' ? 'rtl' : 'ltr');
  applyStaticTranslations();
  if(state){
    state.lang = lang;
    saveState();
    renderAll();
    if(selectedUnit) renderDetail();
    if(studyUnit) renderStudyCard();
    if(practiceQueue.length && practiceIndex < practiceQueue.length) renderExercise();
    const searchInput = document.getElementById('searchInput');
    if(searchInput) searchInput.dispatchEvent(new Event('input'));
  }
}
function toggleLanguage(){
  applyLanguage(currentLang==='ar' ? 'en' : 'ar');
}
